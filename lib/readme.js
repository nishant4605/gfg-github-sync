import { localDate } from './util.js';

const esc = (s) => String(s).replace(/\|/g, '\\|');
const badge = (label, value, color) =>
  `![${label}](https://img.shields.io/badge/${encodeURIComponent(label.replace(/-/g, '--'))}-${encodeURIComponent(String(value).replace(/-/g, '--'))}-${color})`;

export function computeStreak(dates) {
  const set = new Set(dates);
  const d = new Date();
  if (!set.has(localDate(d))) d.setDate(d.getDate() - 1);
  let current = 0;
  while (set.has(localDate(d))) { current++; d.setDate(d.getDate() - 1); }

  let longest = 0, run = 0, prev = null;
  for (const s of [...set].sort()) {
    const t = new Date(s + 'T00:00:00');
    run = prev && Math.round((t - prev) / 864e5) === 1 ? run + 1 : 1;
    longest = Math.max(longest, run);
    prev = t;
  }
  return { current, longest };
}

export function problemReadme(e) {
  return `# ${e.title}

| | |
|---|---|
| **Difficulty** | ${e.difficulty} |
| **Source** | ${e.contest ? `Contest: ${e.contest}` : 'Practice'} |
| **Languages** | ${e.languages.join(', ')} |
| **First solved** | ${e.firstSolved} |
| **Last solved** | ${e.lastSolved} |
${e.tags?.length ? `| **Topics** | ${e.tags.join(', ')} |\n` : ''}
🔗 [Open problem on GeeksforGeeks](${e.link})
`;
}

export function rootReadme(index) {
  const list = Object.values(index.problems);
  const count = (fn) => list.filter(fn).length;
  const streak = computeStreak(index.dates || []);
  const s = index.stats || {};
  const diffs = ['School', 'Basic', 'Easy', 'Medium', 'Hard'];

  const langs = {};
  list.forEach((p) => p.languages.forEach((l) => (langs[l] = (langs[l] || 0) + 1)));
  const topics = {};
  list.forEach((p) => (p.tags || []).forEach((t) => (topics[t] = (topics[t] || 0) + 1)));
  const contests = {};
  list.filter((p) => p.contest).forEach((p) => (contests[p.contest] = contests[p.contest] || []).push(p));

  let md = `# GeeksforGeeks Solutions\n\n`;
  md += [
    badge('Solved', list.length, 'brightgreen'),
    badge('Streak', `${streak.current} days`, 'orange'),
    s.rank != null ? badge('Rank', s.rank, 'blue') : '',
    s.score != null ? badge('Score', s.score, 'purple') : '',
  ].filter(Boolean).join(' ') + '\n\n';

  md += `## Stats\n\n| Metric | Value |\n|---|---|\n`;
  md += `| Problems tracked here | ${list.length} |\n`;
  if (s.solved != null) md += `| Problems solved on GFG | ${s.solved} |\n`;
  if (s.score != null) md += `| Coding score | ${s.score} |\n`;
  if (s.rank != null) md += `| Rank | ${s.rank} |\n`;
  md += `| Current streak | ${streak.current} days |\n| Longest streak | ${streak.longest} days |\n\n`;

  md += `## Difficulty\n\n| Level | Count |\n|---|---|\n`;
  for (const d of diffs) { const c = count((p) => p.difficulty === d); if (c) md += `| ${d} | ${c} |\n`; }
  const unk = count((p) => !diffs.includes(p.difficulty));
  if (unk) md += `| Other | ${unk} |\n`;

  md += `\n## Languages\n\n| Language | Problems |\n|---|---|\n`;
  Object.entries(langs).sort((a, b) => b[1] - a[1]).forEach(([l, c]) => (md += `| ${l} | ${c} |\n`));

  if (Object.keys(topics).length) {
    md += `\n## Topics\n\n| Topic | Problems |\n|---|---|\n`;
    Object.entries(topics).sort((a, b) => b[1] - a[1]).forEach(([t, c]) => (md += `| ${esc(t)} | ${c} |\n`));
  }

  if (Object.keys(contests).length) {
    md += `\n## Contests\n\n| Contest | Problems solved | Last solved |\n|---|---|---|\n`;
    for (const [c, ps] of Object.entries(contests)) {
      md += `| ${esc(c)} | ${ps.length} | ${ps.map((p) => p.lastSolved).sort().pop()} |\n`;
    }
  }

  md += `\n## Problems\n\n| # | Problem | Difficulty | Languages | Solved |\n|---|---|---|---|---|\n`;
  list.sort((a, b) => (b.lastSolved + b.slug).localeCompare(a.lastSolved + a.slug)).forEach((p, i) => {
    md += `| ${list.length - i} | [${esc(p.title)}](${encodeURI(p.path)}) | ${p.difficulty} | ${p.languages.join(', ')} | ${p.lastSolved} |\n`;
  });

  md += `\n---\n_Auto-generated by GFG GitHub Sync. Last updated ${localDate()}._\n`;
  return md;
}
