import { localDate } from './util.js';
import { DIFFICULTIES } from './sync.js';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const shield = (s) => encodeURIComponent(String(s).replace(/-/g, '--').replace(/_/g, '__'));
const days = (n) => `${n} day${n === 1 ? '' : 's'}`;
const badge = (label, value, color) =>
  `![${label}](https://img.shields.io/badge/${shield(label)}-${shield(value)}-${color})`;

/** Count occurrences of the keys produced by `fn` for each item; sorted by count desc, then name. */
function tally(list, fn) {
  const m = {};
  list.forEach((p) => fn(p).forEach((k) => (m[k] = (m[k] || 0) + 1)));
  return Object.entries(m).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

/**
 * Current and longest daily streaks.
 * Current counts back from `today`, or from yesterday if `today` has no solve yet.
 * @param {string[]} dates YYYY-MM-DD local dates
 * @param {Date} [today]
 * @returns {{current: number, longest: number}}
 */
export function computeStreak(dates, today = new Date()) {
  const set = new Set(dates);
  const d = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  if (!set.has(localDate(d))) d.setDate(d.getDate() - 1);
  let current = 0;
  while (set.has(localDate(d))) { current++; d.setDate(d.getDate() - 1); }

  let longest = 0, run = 0, prev = null;
  for (const s of [...set].sort()) {
    const [y, m, day] = s.split('-').map(Number);
    const t = new Date(y, m - 1, day);
    const next = prev && new Date(prev.getFullYear(), prev.getMonth(), prev.getDate() + 1);
    run = next && next.getTime() === t.getTime() ? run + 1 : 1;
    longest = Math.max(longest, run);
    prev = t;
  }
  return { current, longest };
}

/**
 * Per-problem README.
 * @param {Object} e problems.json entry
 * @returns {string}
 */
export function problemReadme(e) {
  const rows = [
    ['Difficulty', e.difficulty],
    ['Source', e.contest ? `Contest: ${e.contest}` : 'Practice'],
    ['Languages', e.languages.join(', ')],
    ['First solved', e.firstSolved],
    ['Last solved', e.lastSolved],
    ...(e.tags?.length ? [['Topics', e.tags.join(', ')]] : []),
  ];
  return `# ${esc(e.title)}\n\n| | |\n|---|---|\n` +
    rows.map(([k, v]) => `| **${k}** | ${esc(v)} |\n`).join('') +
    `\n🔗 [Open problem on GeeksforGeeks](${e.link})\n`;
}

/**
 * Root README with badges and stats tables.
 * @param {{problems: Object, dates: string[], stats: Object|null}} index
 * @param {Date} [now]
 * @returns {string}
 */
export function rootReadme(index, now = new Date()) {
  const list = Object.values(index.problems);
  const streak = computeStreak(index.dates || [], now);
  const s = index.stats || {};
  const table = (head, rows) => rows.length
    ? `| ${head.join(' | ')} |\n|${head.map(() => '---').join('|')}|\n` + rows.map((r) => `| ${r.map(esc).join(' | ')} |\n`).join('')
    : '';

  let md = `# GeeksforGeeks Solutions\n\n`;
  md += [
    badge('Solved', list.length, 'brightgreen'),
    badge('Streak', days(streak.current), 'orange'),
    s.rank != null ? badge('Rank', s.rank, 'blue') : '',
    s.score != null ? badge('Score', s.score, 'purple') : '',
  ].filter(Boolean).join(' ') + '\n\n';

  md += `## Stats\n\n` + table(['Metric', 'Value'], [
    ['Problems tracked here', list.length],
    s.solved != null && ['Problems solved on GFG', s.solved],
    s.score != null && ['Coding score', s.score],
    s.rank != null && ['Rank', s.rank],
    ['Current streak', days(streak.current)],
    ['Longest streak', days(streak.longest)],
  ].filter(Boolean));

  const diffRows = DIFFICULTIES.map((d) => [d, list.filter((p) => p.difficulty === d).length]);
  diffRows.push(['Other', list.filter((p) => !DIFFICULTIES.includes(p.difficulty)).length]);
  md += `\n## Difficulty\n\n` + table(['Level', 'Count'], diffRows.filter(([, c]) => c));

  md += `\n## Languages\n\n` + table(['Language', 'Problems'], tally(list, (p) => p.languages));

  const topics = tally(list, (p) => p.tags || []);
  if (topics.length) md += `\n## Topics\n\n` + table(['Topic', 'Problems'], topics);

  const contests = {};
  list.filter((p) => p.contest).forEach((p) => (contests[p.contest] ||= []).push(p.lastSolved));
  const contestRows = Object.entries(contests).map(([c, ds]) => [c, ds.length, ds.sort().at(-1)]);
  if (contestRows.length) md += `\n## Contests\n\n` + table(['Contest', 'Problems solved', 'Last solved'], contestRows);

  const sorted = [...list].sort((a, b) => b.lastSolved.localeCompare(a.lastSolved) || a.title.localeCompare(b.title));
  md += `\n## Problems\n\n| # | Problem | Difficulty | Languages | Solved |\n|---|---|---|---|---|\n`;
  sorted.forEach((p, i) => {
    md += `| ${i + 1} | [${esc(p.title)}](${encodeURI(p.path)}) | ${esc(p.difficulty)} | ${esc(p.languages.join(', '))} | ${p.lastSolved} |\n`;
  });

  md += `\n---\n_Auto-generated by GFG GitHub Sync. Last updated ${localDate(now)}._\n`;
  return md;
}
